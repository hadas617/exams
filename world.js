function startFactAutoScroll(containerId, textId) {
  const container = document.getElementById(containerId);
  const text = document.getElementById(textId);
  
  clearInterval(autoScrollInterval);
  if (text) text.style.top = "0px"; 
  if (!container || !text) return;

  setTimeout(() => {
    const titleElement = container.querySelector('.note-title');
    const titleHeight = titleElement ? titleElement.getBoundingClientRect().height : 0;
    
    // גובה האזור הויזואלי שנשאר לטקסט
    const containerHeight = container.getBoundingClientRect().height - titleHeight;
    const textHeight = text.scrollHeight; 
    
    if (textHeight > containerHeight) {
      // גדלנו את מרווח הביטחון מ-15 ל-45 פיקסלים כדי שהטקסט יגלול רחוק יותר למעלה
      const maxScroll = (textHeight - containerHeight) + 45;
      
      let currentScroll = 0;
      let state = "paused-top"; 
      let holdCounter = 0;
      
      autoScrollInterval = setInterval(() => {
        if (state === "paused-top") {
          holdCounter++;
          if (holdCounter >= 30) { 
            state = "scrolling";
            holdCounter = 0;
          }
        } 
        else if (state === "scrolling") {
          currentScroll += 0.4; 
          text.style.top = `-${currentScroll}px`;
          if (currentScroll >= maxScroll) {
            state = "paused-bottom";
          }
        } 
        else if (state === "paused-bottom") {
          holdCounter++;
          if (holdCounter >= 80) { 
            text.style.top = "0px";
            currentScroll = 0;
            holdCounter = 0;
            state = "paused-top";
          }
        }
      }, 50);
    }
  }, 400);
}

